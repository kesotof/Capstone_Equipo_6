CREATE INDEX idx_solicitud_etapa ON solicitud (flujo_etapa_id);

-- Historial inmutable de transiciones; el CHECK implementa la máquina de estados
CREATE TABLE historial_transicion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id   UUID        NOT NULL REFERENCES solicitud(id),
    flujo_etapa_id BIGINT      NOT NULL REFERENCES flujo_etapa(id),
    accion         VARCHAR(30) NOT NULL REFERENCES accion_transicion(codigo),
    estado_origen  VARCHAR(30) REFERENCES estado_solicitud(codigo),
    estado_destino VARCHAR(30) NOT NULL REFERENCES estado_solicitud(codigo),
    usuario_id     UUID        NOT NULL REFERENCES usuario(id),
    observacion    TEXT,
    dentro_sla     BOOLEAN,
    metadata       JSONB       DEFAULT '{}' NOT NULL,
    created_at     TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT chk_hist_maquina_estados CHECK (
        (accion = 'REGISTRAR'            AND estado_origen IS NULL                  AND estado_destino = 'PENDIENTE_REVISION')
     OR (accion = 'SOLICITAR_CORRECCION' AND estado_origen = 'PENDIENTE_REVISION'   AND estado_destino = 'CORRECCION_REQUERIDA')
     OR (accion = 'CORREGIR'             AND estado_origen = 'CORRECCION_REQUERIDA' AND estado_destino = 'PENDIENTE_REVISION')
     OR (accion = 'APROBAR'              AND estado_origen = 'PENDIENTE_REVISION'   AND estado_destino IN ('PENDIENTE_REVISION', 'APROBADO'))
     OR (accion = 'RECHAZAR'             AND estado_origen = 'PENDIENTE_REVISION'   AND estado_destino = 'RECHAZADO')),
    CONSTRAINT chk_hist_observacion_obligatoria CHECK (
        accion NOT IN ('SOLICITAR_CORRECCION', 'RECHAZAR') OR (observacion IS NOT NULL AND char_length(btrim(observacion)) > 0))
);
CREATE INDEX idx_hist_solicitud ON historial_transicion (solicitud_id, created_at);
CREATE INDEX idx_hist_etapa ON historial_transicion (flujo_etapa_id);
CREATE INDEX idx_hist_usuario ON historial_transicion (usuario_id);
CREATE INDEX idx_hist_created ON historial_transicion (created_at);

-- Documento versionado: una nueva versión reemplaza a la anterior sin borrarla
CREATE TABLE documento (
    id                      UUID         DEFAULT gen_random_uuid() PRIMARY KEY,
    historial_transicion_id BIGINT       NOT NULL REFERENCES historial_transicion(id),
    reemplaza_documento_id  UUID         UNIQUE REFERENCES documento(id),
    version                 INTEGER      DEFAULT 1 NOT NULL,
    nombre_archivo          VARCHAR(255) NOT NULL,
    content_type            VARCHAR(100) NOT NULL CHECK (content_type IN (
        'application/pdf',
        'application/msword',
        'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
        'application/xml', 'text/xml',
        'text/plain')),
    storage_key             VARCHAR(500) NOT NULL UNIQUE,
    size_bytes              BIGINT       NOT NULL CHECK (size_bytes >= 0),
    checksum_sha256         VARCHAR(64)  NOT NULL CHECK (char_length(checksum_sha256) = 64),
    storage_version_id      VARCHAR(100),
    plantilla_version_id    BIGINT       REFERENCES plantilla_version(id),
    datos_plantilla         JSONB,
    CONSTRAINT chk_doc_version CHECK (
        (reemplaza_documento_id IS NULL AND version = 1) OR
        (reemplaza_documento_id IS NOT NULL AND version > 1)),
    CONSTRAINT chk_doc_plantilla CHECK (
        (plantilla_version_id IS NULL AND datos_plantilla IS NULL) OR
        (plantilla_version_id IS NOT NULL AND datos_plantilla IS NOT NULL))
);
CREATE INDEX idx_doc_transicion ON documento (historial_transicion_id);
CREATE INDEX idx_doc_plantilla ON documento (plantilla_version_id);

-- Solicitud compartida con un usuario o con un área (exactamente uno de los dos)

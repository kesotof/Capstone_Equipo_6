CREATE TABLE tipo_evento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(50)  NOT NULL UNIQUE,
    categoria   VARCHAR(30)  NOT NULL CHECK (categoria IN ('AUTENTICACION', 'ADMINISTRACION', 'FLUJO', 'ACCESO')),
    descripcion VARCHAR(255)
);

CREATE TABLE tipo_notificacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(50)  NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

-- Tipo de documento: define el prefijo del correlativo y el plazo SLA en días hábiles
CREATE TABLE tipo_documento (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(100) NOT NULL,
    descripcion        VARCHAR(500),
    prefijo            VARCHAR(10)  NOT NULL UNIQUE,
    plazo_dias_habiles INTEGER      NOT NULL CHECK (plazo_dias_habiles > 0),
    ultimo_correlativo BIGINT       DEFAULT 0 NOT NULL CHECK (ultimo_correlativo >= 0),
    activo             BOOLEAN      DEFAULT true NOT NULL,
    lock_version       BIGINT       DEFAULT 0 NOT NULL,
    created_at         TIMESTAMPTZ  DEFAULT now() NOT NULL,
    updated_at         TIMESTAMPTZ  DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uq_tipo_documento_nombre ON tipo_documento (lower(btrim(nombre)));

CREATE TABLE estado_solicitud (
    codigo   VARCHAR(30)  PRIMARY KEY,
    etiqueta VARCHAR(100) NOT NULL,
    orden    INTEGER      NOT NULL,
    es_final BOOLEAN      DEFAULT false NOT NULL
);

CREATE TABLE accion_transicion (
    codigo   VARCHAR(30)  PRIMARY KEY,
    etiqueta VARCHAR(100) NOT NULL
);

CREATE TABLE permiso (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurso     VARCHAR(50)  NOT NULL,
    accion      VARCHAR(30)  NOT NULL,
    descripcion VARCHAR(255),
    ambito      VARCHAR(20)  NOT NULL CHECK (ambito IN ('AREA_O_GLOBAL', 'SOLO_GLOBAL')),
    CONSTRAINT permiso_recurso_accion_un UNIQUE (recurso, accion)
);


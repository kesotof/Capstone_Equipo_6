-- 2. ORGANIZACIÓN Y CONTROL DE ACCESO (RBAC)
-- =============================================================================

-- Áreas jerárquicas (organigrama): cada área puede tener un área padre
CREATE TABLE area (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    descripcion   VARCHAR(500),
    area_padre_id BIGINT REFERENCES area(id),
    activo        BOOLEAN      DEFAULT true NOT NULL,
    lock_version  BIGINT       DEFAULT 0 NOT NULL,
    created_at    TIMESTAMPTZ  DEFAULT now() NOT NULL,
    updated_at    TIMESTAMPTZ  DEFAULT now() NOT NULL,
    CONSTRAINT chk_area_padre CHECK (area_padre_id IS NULL OR area_padre_id <> id),
    CONSTRAINT chk_area_nombre_no_vacio CHECK (char_length(btrim(nombre)) > 0)
);
CREATE UNIQUE INDEX uq_area_nombre ON area (lower(btrim(nombre)));
CREATE INDEX idx_area_padre ON area (area_padre_id);

-- Usuario de negocio; las credenciales viven en Keycloak (vínculo por keycloak_id)
CREATE TABLE usuario (
    id           UUID         DEFAULT gen_random_uuid() PRIMARY KEY,
    keycloak_id  VARCHAR(255) UNIQUE,
    email        VARCHAR(255) NOT NULL UNIQUE,
    rut          VARCHAR(12)  UNIQUE,
    nombre       VARCHAR(100) NOT NULL,
    apellido     VARCHAR(100) NOT NULL,
    area_id      BIGINT       REFERENCES area(id),
    activo       BOOLEAN      DEFAULT true NOT NULL,
    lock_version BIGINT       DEFAULT 0 NOT NULL,
    created_at   TIMESTAMPTZ  DEFAULT now() NOT NULL,
    updated_at   TIMESTAMPTZ  DEFAULT now() NOT NULL
);
CREATE INDEX idx_usuario_area ON usuario (area_id);

CREATE TABLE area_jefatura (
    area_id    BIGINT      NOT NULL REFERENCES area(id),
    usuario_id UUID        NOT NULL REFERENCES usuario(id),
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    PRIMARY KEY (area_id, usuario_id)
);
CREATE INDEX idx_jefatura_usuario ON area_jefatura (usuario_id);

CREATE TABLE rol (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(50)   NOT NULL UNIQUE,
    nombre              VARCHAR(100)  NOT NULL,
    descripcion         VARCHAR(1000),
    sistema             BOOLEAN       DEFAULT false NOT NULL,
    asignacion          VARCHAR(20)   DEFAULT 'MANUAL' NOT NULL CHECK (asignacion IN ('MANUAL', 'AUTO_JEFATURA')),
    ambito              VARCHAR(20)   DEFAULT 'AREA_O_GLOBAL' NOT NULL CHECK (ambito IN ('AREA_O_GLOBAL', 'SOLO_GLOBAL')),
    permisos_bloqueados BOOLEAN       DEFAULT false NOT NULL,
    activo              BOOLEAN       DEFAULT true NOT NULL,
    lock_version        BIGINT        DEFAULT 0 NOT NULL,
    created_at          TIMESTAMPTZ   DEFAULT now() NOT NULL,
    updated_at          TIMESTAMPTZ   DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uq_rol_nombre ON rol (lower(btrim(nombre)));
CREATE UNIQUE INDEX uq_rol_auto_jefatura ON rol (asignacion) WHERE asignacion = 'AUTO_JEFATURA';

CREATE TABLE rol_permiso (
    rol_id     BIGINT NOT NULL REFERENCES rol(id) ON DELETE CASCADE,
    permiso_id BIGINT NOT NULL REFERENCES permiso(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);

-- Asignación de rol: sobre un área (y sus subáreas) o global (area_id NULL)
CREATE TABLE usuario_rol (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    UUID        NOT NULL REFERENCES usuario(id),
    rol_id        BIGINT      NOT NULL REFERENCES rol(id),
    area_id       BIGINT      REFERENCES area(id),
    vigente_hasta TIMESTAMPTZ,
    otorgado_por  UUID        NOT NULL REFERENCES usuario(id),
    created_at    TIMESTAMPTZ DEFAULT now() NOT NULL,
    CONSTRAINT uq_usuario_rol UNIQUE NULLS NOT DISTINCT (usuario_id, rol_id, area_id)
);
CREATE INDEX idx_usuario_rol_rol  ON usuario_rol (rol_id);
CREATE INDEX idx_usuario_rol_area ON usuario_rol (area_id);

-- Versión de la política de acceso: se incrementa ante cada cambio RBAC (fila única)
CREATE TABLE control_politica (
    id         INTEGER     PRIMARY KEY CHECK (id = 1),
    version    BIGINT      DEFAULT 1 NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);
INSERT INTO control_politica (id, version, updated_at) VALUES (1, 1, now());


-- Jerarquía de áreas: cada área con todas sus descendientes (incluida ella misma)
CREATE VIEW v_area_descendiente AS
WITH RECURSIVE arbol AS (
    SELECT id AS ancestro_id, id AS area_id
      FROM area
    UNION ALL
    SELECT a.ancestro_id, h.id AS area_id
      FROM arbol a
      JOIN area h ON h.area_padre_id = a.area_id
) CYCLE area_id SET es_ciclo USING ruta
SELECT ancestro_id, area_id
  FROM arbol
 WHERE NOT es_ciclo;

-- Permisos efectivos por usuario y área, con su origen (rol de área, rol global o jefatura)
CREATE VIEW v_permiso_efectivo AS
SELECT ur.usuario_id, p.recurso, p.accion, d.area_id,
       'ROL'::varchar(20) AS origen, r.id AS rol_id, ur.area_id AS area_asignada_id,
       md5(concat_ws(':', ur.usuario_id, p.recurso, p.accion, coalesce(d.area_id, 0), 'ROL', r.id, coalesce(ur.area_id, 0))) AS id
  FROM usuario_rol ur
  JOIN rol r          ON r.id = ur.rol_id AND r.activo
  JOIN rol_permiso rp ON rp.rol_id = r.id
  JOIN permiso p      ON p.id = rp.permiso_id
  JOIN v_area_descendiente d ON d.ancestro_id = ur.area_id
 WHERE ur.vigente_hasta IS NULL OR ur.vigente_hasta > now()
UNION ALL
SELECT ur.usuario_id, p.recurso, p.accion, NULL::bigint AS area_id,
       'ROL_GLOBAL'::varchar(20) AS origen, r.id AS rol_id, NULL::bigint AS area_asignada_id,
       md5(concat_ws(':', ur.usuario_id, p.recurso, p.accion, 0, 'ROL_GLOBAL', r.id, 0)) AS id
  FROM usuario_rol ur
  JOIN rol r          ON r.id = ur.rol_id AND r.activo
  JOIN rol_permiso rp ON rp.rol_id = r.id
  JOIN permiso p      ON p.id = rp.permiso_id
 WHERE ur.area_id IS NULL AND (ur.vigente_hasta IS NULL OR ur.vigente_hasta > now())
UNION ALL
SELECT j.usuario_id, p.recurso, p.accion, d.area_id,
       'JEFATURA'::varchar(20) AS origen, r.id AS rol_id, j.area_id AS area_asignada_id,
       md5(concat_ws(':', j.usuario_id, p.recurso, p.accion, coalesce(d.area_id, 0), 'JEFATURA', r.id, coalesce(j.area_id, 0))) AS id
  FROM area_jefatura j
  JOIN usuario u      ON u.id = j.usuario_id AND u.activo
  JOIN rol r          ON r.asignacion = 'AUTO_JEFATURA' AND r.activo
  JOIN rol_permiso rp ON rp.rol_id = r.id
  JOIN permiso p      ON p.id = rp.permiso_id
  JOIN v_area_descendiente d ON d.ancestro_id = j.area_id;

-- Revisores de la etapa actual de cada solicitud. En modo jefatura se usa la
-- jefatura del área de la solicitud o, si no tiene, la del ancestro más cercano
CREATE VIEW v_revisor_solicitud AS
SELECT s.id AS solicitud_id,
       s.flujo_etapa_id,
       fer.usuario_id
  FROM solicitud s
  JOIN flujo_etapa fe ON fe.id = s.flujo_etapa_id AND fe.modo_revisor = 'LISTA'
  JOIN flujo_etapa_revisor fer ON fer.flujo_etapa_id = fe.id
  JOIN usuario u ON u.id = fer.usuario_id AND u.activo
UNION ALL
SELECT s.id AS solicitud_id,
       s.flujo_etapa_id,
       jefes.usuario_id
  FROM solicitud s
  JOIN flujo_etapa fe ON fe.id = s.flujo_etapa_id AND fe.modo_revisor = 'JEFATURA_AREA_SOLICITUD'
  CROSS JOIN LATERAL (
      WITH RECURSIVE rama AS (
          SELECT a.id, a.area_padre_id, 0 AS distancia
            FROM area a
           WHERE a.id = s.area_id
          UNION ALL
          SELECT p.id, p.area_padre_id, r.distancia + 1
            FROM area p
            JOIN rama r ON p.id = r.area_padre_id
      ),
      jefes_con_distancia AS (
          SELECT j.usuario_id, r.distancia
            FROM rama r
            JOIN area_jefatura j ON j.area_id = r.id
            JOIN usuario u ON u.id = j.usuario_id AND u.activo
      ),
      distancia_minima AS (
          SELECT MIN(distancia) AS min_dist FROM jefes_con_distancia
      )
      SELECT jd.usuario_id
        FROM jefes_con_distancia jd
        JOIN distancia_minima dm ON jd.distancia = dm.min_dist
  ) jefes;

-- Quién puede ver cada solicitud y por qué motivo
CREATE VIEW v_acceso_solicitud AS
SELECT s.id AS solicitud_id, s.usuario_id, 'EMISOR'::varchar(20) AS motivo
  FROM solicitud s
UNION ALL
SELECT s.id, rs.usuario_id, 'REVISOR'::varchar(20)
  FROM solicitud s
  JOIN v_revisor_solicitud rs ON rs.solicitud_id = s.id AND rs.flujo_etapa_id = s.flujo_etapa_id
UNION ALL
SELECT DISTINCT h.solicitud_id, h.usuario_id, 'PARTICIPANTE'::varchar(20)
  FROM historial_transicion h
UNION ALL
SELECT c.solicitud_id, c.usuario_id, 'COMPARTIDA'::varchar(20)
  FROM solicitud_compartida c
 WHERE c.usuario_id IS NOT NULL
UNION ALL
SELECT c.solicitud_id, u.id, 'COMPARTIDA_AREA'::varchar(20)
  FROM solicitud_compartida c
  JOIN usuario u ON u.area_id = c.area_id
UNION ALL
SELECT s.id, pe.usuario_id, pe.origen
  FROM solicitud s
  JOIN v_permiso_efectivo pe
    ON pe.recurso = 'SOLICITUD'
   AND pe.accion = 'VER'
   AND (pe.area_id = s.area_id OR pe.area_id IS NULL);

-- Quién puede descargar documentos (solo quien además puede ver la solicitud)
CREATE VIEW v_acceso_descarga AS
SELECT ac.solicitud_id, ac.usuario_id, ac.motivo
  FROM v_acceso_solicitud ac
 WHERE ac.motivo IN ('EMISOR', 'REVISOR', 'PARTICIPANTE')
UNION
SELECT s.id AS solicitud_id, pe.usuario_id, pe.origen AS motivo
  FROM solicitud s
  JOIN v_permiso_efectivo pe
    ON pe.recurso = 'DOCUMENTO'
   AND pe.accion = 'DESCARGAR'
   AND (pe.area_id = s.area_id OR pe.area_id IS NULL)
  JOIN v_acceso_solicitud ac
    ON ac.solicitud_id = s.id
   AND ac.usuario_id = pe.usuario_id;

-- Flujos utilizables: activos, con etapas y con revisores activos en sus etapas LISTA
CREATE VIEW v_flujo_disponible AS
SELECT f.id, f.nombre, f.version, f.area_id
  FROM flujo_definicion f
 WHERE f.activo
   AND EXISTS (SELECT 1 FROM flujo_etapa e WHERE e.flujo_definicion_id = f.id)
   AND NOT EXISTS (
        SELECT 1
          FROM flujo_etapa e
         WHERE e.flujo_definicion_id = f.id
           AND e.modo_revisor = 'LISTA'
           AND NOT EXISTS (
                SELECT 1
                  FROM flujo_etapa_revisor r
                  JOIN usuario u ON u.id = r.usuario_id
                 WHERE r.flujo_etapa_id = e.id
                   AND u.activo));

-- Flujos que puede usar cada usuario según el área del flujo y la suya
CREATE VIEW v_flujo_disponible_usuario AS
SELECT f.id AS flujo_id, u.id AS usuario_id
  FROM v_flujo_disponible f
  CROSS JOIN usuario u
 WHERE u.activo
   AND (
       f.area_id IS NULL
       OR (u.area_id IS NOT NULL AND EXISTS (
           SELECT 1
             FROM v_area_descendiente d
            WHERE d.ancestro_id = f.area_id
              AND d.area_id = u.area_id
       ))
   );

-- Bandeja de cada revisor: solicitudes pendientes en su etapa
CREATE VIEW v_bandeja_revision AS
SELECT rs.usuario_id AS revisor_id,
       s.id          AS solicitud_id,
       s.correlativo, s.titulo, s.usuario_id AS emisor_id, s.area_id,
       s.tipo_documento_id, s.flujo_etapa_id, s.deadline, s.created_at
  FROM solicitud s
  JOIN v_revisor_solicitud rs ON rs.solicitud_id = s.id AND rs.flujo_etapa_id = s.flujo_etapa_id
 WHERE s.estado = 'PENDIENTE_REVISION';

-- Última versión de cada documento
CREATE VIEW v_documento_vigente AS
SELECT d.id, d.version, d.nombre_archivo, d.content_type, d.storage_key,
       d.size_bytes, d.checksum_sha256, d.reemplaza_documento_id,
       h.solicitud_id, h.flujo_etapa_id,
       h.usuario_id AS subido_por, h.created_at AS subido_en
  FROM documento d
  JOIN historial_transicion h ON h.id = d.historial_transicion_id
 WHERE NOT EXISTS (SELECT 1 FROM documento r WHERE r.reemplaza_documento_id = d.id);

-- Última versión de cada plantilla activa
CREATE VIEW v_plantilla_vigente AS
SELECT p.id AS plantilla_id, p.nombre, p.descripcion, p.tipo_documento_id, p.area_id,
       v.id AS plantilla_version_id, v.version, v.storage_key, v.esquema_campos
  FROM plantilla p
  JOIN plantilla_version v ON v.plantilla_id = p.id
 WHERE p.activo
   AND v.version = (SELECT MAX(v2.version) FROM plantilla_version v2 WHERE v2.plantilla_id = p.id);


-- Flujo de aprobación: global (area_id NULL) o propio de un área
CREATE TABLE flujo_definicion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(150) NOT NULL,
    version      INTEGER      DEFAULT 1 NOT NULL CHECK (version >= 1),
    descripcion  TEXT,
    area_id      BIGINT       REFERENCES area(id),
    activo       BOOLEAN      DEFAULT true NOT NULL,
    lock_version BIGINT       DEFAULT 0 NOT NULL,
    created_at   TIMESTAMPTZ  DEFAULT now() NOT NULL,
    updated_at   TIMESTAMPTZ  DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uq_flujo_nombre_version ON flujo_definicion (lower(btrim(nombre)), version);
CREATE INDEX idx_flujodef_area ON flujo_definicion (area_id);

-- Etapa: revisores de una lista fija (LISTA) o la jefatura del área de la solicitud
CREATE TABLE flujo_etapa (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flujo_definicion_id BIGINT       NOT NULL REFERENCES flujo_definicion(id) ON DELETE CASCADE,
    orden               INTEGER      NOT NULL CHECK (orden >= 1),
    nombre              VARCHAR(150) NOT NULL,
    modo_revisor        VARCHAR(30)  DEFAULT 'LISTA' NOT NULL CHECK (modo_revisor IN ('LISTA', 'JEFATURA_AREA_SOLICITUD')),
    CONSTRAINT unq_flujo_orden UNIQUE (flujo_definicion_id, orden),
    CONSTRAINT unq_flujo_etapa_id UNIQUE (flujo_definicion_id, id)
);

CREATE TABLE flujo_etapa_revisor (
    flujo_etapa_id BIGINT      NOT NULL REFERENCES flujo_etapa(id) ON DELETE CASCADE,
    usuario_id     UUID        NOT NULL REFERENCES usuario(id),
    created_at     TIMESTAMPTZ DEFAULT now() NOT NULL,
    PRIMARY KEY (flujo_etapa_id, usuario_id)
);
CREATE INDEX idx_revisor_usuario ON flujo_etapa_revisor (usuario_id);

CREATE TABLE plantilla (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(150) NOT NULL,
    descripcion       VARCHAR(500),
    tipo_documento_id BIGINT       NOT NULL REFERENCES tipo_documento(id),
    area_id           BIGINT       REFERENCES area(id),
    activo            BOOLEAN      DEFAULT true NOT NULL,
    lock_version      BIGINT       DEFAULT 0 NOT NULL,
    created_at        TIMESTAMPTZ  DEFAULT now() NOT NULL,
    updated_at        TIMESTAMPTZ  DEFAULT now() NOT NULL
);
CREATE UNIQUE INDEX uq_plantilla_nombre ON plantilla (lower(btrim(nombre)));
CREATE INDEX idx_plantilla_tipodoc ON plantilla (tipo_documento_id);
CREATE INDEX idx_plantilla_area ON plantilla (area_id);

-- Versión publicada de una plantilla .docx; el archivo se guarda en MinIO (storage_key)
CREATE TABLE plantilla_version (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plantilla_id    BIGINT        NOT NULL REFERENCES plantilla(id) ON DELETE CASCADE,
    version         INTEGER       NOT NULL CHECK (version >= 1),
    storage_key     VARCHAR(500)  NOT NULL UNIQUE,
    content_type    VARCHAR(100)  NOT NULL CHECK (content_type = 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'),
    checksum_sha256 VARCHAR(64)   NOT NULL CHECK (char_length(checksum_sha256) = 64),
    esquema_campos  JSONB         NOT NULL,
    creado_por      UUID          NOT NULL REFERENCES usuario(id),
    created_at      TIMESTAMPTZ   DEFAULT now() NOT NULL,
    CONSTRAINT plantilla_version_un UNIQUE (plantilla_id, version)
);
CREATE INDEX idx_pltver_creador ON plantilla_version (creado_por);


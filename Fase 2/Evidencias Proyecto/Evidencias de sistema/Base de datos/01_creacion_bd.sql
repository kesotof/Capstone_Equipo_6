-- 7.2 Los datos de origen de una solicitud no se modifican después de registrarla
CREATE FUNCTION fn_solicitud_datos_origen()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.correlativo         IS DISTINCT FROM OLD.correlativo
    OR NEW.usuario_id          IS DISTINCT FROM OLD.usuario_id
    OR NEW.area_id             IS DISTINCT FROM OLD.area_id
    OR NEW.tipo_documento_id   IS DISTINCT FROM OLD.tipo_documento_id
    OR NEW.flujo_definicion_id IS DISTINCT FROM OLD.flujo_definicion_id
    OR NEW.created_at          IS DISTINCT FROM OLD.created_at
    THEN
        RAISE EXCEPTION 'Emisor, área, tipo, flujo, correlativo y fecha de creación de la solicitud no pueden modificarse' USING ERRCODE = 'CB007';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_solicitud_datos_origen
BEFORE UPDATE ON solicitud
FOR EACH ROW EXECUTE FUNCTION fn_solicitud_datos_origen();

-- 7.3 Un flujo con solicitudes no puede cambiar sus etapas (se crea una nueva versión)
CREATE FUNCTION fn_flujo_etapa_en_uso()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_flujo_id BIGINT;
BEGIN
    IF TG_OP = 'UPDATE'
       AND NEW.orden = OLD.orden
       AND NEW.flujo_definicion_id = OLD.flujo_definicion_id
    THEN
        RETURN NEW;
    END IF;

    v_flujo_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.flujo_definicion_id ELSE NEW.flujo_definicion_id END;

    IF EXISTS (SELECT 1 FROM solicitud WHERE flujo_definicion_id = v_flujo_id) THEN
        RAISE EXCEPTION 'El flujo tiene solicitudes; cree una nueva versión en lugar de modificar sus etapas' USING ERRCODE = 'CB006';
    END IF;

    RETURN COALESCE(NEW, OLD);
END;
$$;
CREATE TRIGGER trg_flujo_etapa_en_uso
BEFORE INSERT OR UPDATE OR DELETE ON flujo_etapa
FOR EACH ROW EXECUTE FUNCTION fn_flujo_etapa_en_uso();

-- 7.4 Actor válido en cada transición: solo el emisor registra o corrige; solo
--     un revisor asignado o el administrador global aprueba, rechaza o pide corrección
CREATE FUNCTION fn_historial_actor_valido()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_emisor      UUID;
    v_flujo_sol   BIGINT;
    v_flujo_etapa BIGINT;
BEGIN
    SELECT usuario_id, flujo_definicion_id
      INTO v_emisor, v_flujo_sol
      FROM solicitud
     WHERE id = NEW.solicitud_id;

    SELECT flujo_definicion_id
      INTO v_flujo_etapa
      FROM flujo_etapa
     WHERE id = NEW.flujo_etapa_id;

    IF v_flujo_etapa IS DISTINCT FROM v_flujo_sol THEN
        RAISE EXCEPTION 'La etapa no pertenece al flujo de la solicitud' USING ERRCODE = 'CB010';
    END IF;

    IF NEW.accion IN ('REGISTRAR', 'CORREGIR') THEN
        IF NEW.usuario_id IS DISTINCT FROM v_emisor THEN
            RAISE EXCEPTION 'Solo el emisor puede registrar o corregir la solicitud' USING ERRCODE = 'CB011';
        END IF;
    ELSIF NOT es_revisor(NEW.solicitud_id, NEW.flujo_etapa_id, NEW.usuario_id)
      AND NOT es_admin_global(NEW.usuario_id) THEN
        RAISE EXCEPTION 'El usuario no es revisor asignado de esta etapa' USING ERRCODE = 'CB012';
    END IF;

    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_historial_actor_valido
BEFORE INSERT ON historial_transicion
FOR EACH ROW EXECUTE FUNCTION fn_historial_actor_valido();

-- 7.5 Reglas de asignación de roles
CREATE FUNCTION fn_usuario_rol_valido()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_asignacion VARCHAR(20);
    v_ambito     VARCHAR(20);
BEGIN
    SELECT asignacion, ambito
      INTO v_asignacion, v_ambito
      FROM rol
     WHERE id = NEW.rol_id;

    IF v_asignacion = 'AUTO_JEFATURA' THEN
        RAISE EXCEPTION 'El rol JEFATURA_AREA es automático y no puede asignarse manualmente' USING ERRCODE = 'CB013';
    END IF;

    IF v_ambito = 'SOLO_GLOBAL' AND NEW.area_id IS NOT NULL THEN
        RAISE EXCEPTION 'Este rol solo puede asignarse a nivel global' USING ERRCODE = 'CB013';
    END IF;

    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_usuario_rol_valido
BEFORE INSERT OR UPDATE ON usuario_rol
FOR EACH ROW EXECUTE FUNCTION fn_usuario_rol_valido();

-- 7.6 Los roles de sistema no se eliminan ni cambian su código o tipo de asignación
CREATE FUNCTION fn_rol_protegido()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.sistema THEN
        IF TG_OP = 'DELETE' THEN
            RAISE EXCEPTION 'Los roles de sistema no pueden eliminarse' USING ERRCODE = 'CB014';
        ELSIF NEW.codigo IS DISTINCT FROM OLD.codigo OR NEW.asignacion IS DISTINCT FROM OLD.asignacion THEN
            RAISE EXCEPTION 'Los roles de sistema no pueden modificarse en sus propiedades estructurales' USING ERRCODE = 'CB014';
        END IF;
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$;
CREATE TRIGGER trg_rol_protegido
BEFORE UPDATE OR DELETE ON rol
FOR EACH ROW EXECUTE FUNCTION fn_rol_protegido();

-- 7.7 Los permisos de un rol bloqueado (ADMIN_SISTEMA) no se modifican
CREATE FUNCTION fn_rol_permiso_protegido()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE

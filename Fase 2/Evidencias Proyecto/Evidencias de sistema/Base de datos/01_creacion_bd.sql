    usuario_id          UUID         NOT NULL REFERENCES usuario(id),
    area_id             BIGINT       NOT NULL REFERENCES area(id),
    titulo              VARCHAR(255) NOT NULL,
    descripcion         TEXT,
    estado              VARCHAR(30)  NOT NULL REFERENCES estado_solicitud(codigo),
    deadline            TIMESTAMPTZ,
    lock_version        BIGINT       DEFAULT 0 NOT NULL,
    created_at          TIMESTAMPTZ  DEFAULT now() NOT NULL,
    updated_at          TIMESTAMPTZ  DEFAULT now() NOT NULL,
    -- La etapa actual debe pertenecer al flujo de la solicitud
    CONSTRAINT fk_solicitud_flujo_etapa FOREIGN KEY (flujo_definicion_id, flujo_etapa_id)
        REFERENCES flujo_etapa (flujo_definicion_id, id)

CREATE FUNCTION es_revisor(p_solicitud UUID, p_etapa BIGINT, p_usuario UUID)
RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1
          FROM v_revisor_solicitud rs
         WHERE rs.solicitud_id = p_solicitud
           AND rs.flujo_etapa_id = p_etapa
           AND rs.usuario_id = p_usuario
    );
$$;

-- Administrador global: rol ADMIN_SISTEMA vigente (reflejo del rol ADMIN de Keycloak)
CREATE FUNCTION es_admin_global(p_usuario UUID)
RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1
          FROM usuario_rol ur
          JOIN rol r ON r.id = ur.rol_id
         WHERE ur.usuario_id = p_usuario
           AND r.codigo IN ('ADMIN', 'ADMIN_SISTEMA')
           AND (ur.vigente_hasta IS NULL OR ur.vigente_hasta > now())
    );
$$;


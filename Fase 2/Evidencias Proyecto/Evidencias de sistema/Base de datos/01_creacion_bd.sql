    IF v_bloqueados THEN
        RAISE EXCEPTION 'Los permisos de este rol están bloqueados y no pueden modificarse' USING ERRCODE = 'CB014';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$;
CREATE TRIGGER trg_rol_permiso_protegido
BEFORE INSERT OR UPDATE OR DELETE ON rol_permiso
FOR EACH ROW EXECUTE FUNCTION fn_rol_permiso_protegido();

